/** Great-circle distance (km) between two sites using core.siteFrame unit vectors (mean radius). */
function distKm(a, b) {
  const u = core.siteFrame(a).up, v = core.siteFrame(b).up;
  return Math.acos(Math.max(-1, Math.min(1, u[0] * v[0] + u[1] * v[1] + u[2] * v[2]))) * core.R_MOON_KM;
}
/** East / north offset (km) of b seen from a, in a's local frame (for placing dots on the ±10 km map). */
function enKm(a, b) {
  const fa = core.siteFrame(a), v = core.siteFrame(b).up, d = [v[0] - fa.up[0], v[1] - fa.up[1], v[2] - fa.up[2]];
  return { e: (d[0] * fa.east[0] + d[1] * fa.east[1] + d[2] * fa.east[2]) * core.R_MOON_KM, n: (d[0] * fa.north[0] + d[1] * fa.north[1] + d[2] * fa.north[2]) * core.R_MOON_KM };
}
